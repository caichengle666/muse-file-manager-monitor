describe("assessCommand", () => {
  test.each(autoRun)("auto-runs: %s", (command) => {
    expect(assessCommand(command)).toEqual({ requiresConfirmation: false, reason: expect.any(String) });
  });

  test.each(needsConfirmation)("requires confirmation: %s", (command) => {
    expect(assessCommand(command).requiresConfirmation).toBe(true);
  });

  test("explains redirection in the reason", () => {
    expect(assessCommand("echo hi > file.txt").reason).toContain("重定向");
  });

  test("explains dynamic command names in the reason", () => {
    expect(assessCommand("$CMD -rf x").reason).toContain("动态");
  });

  test("treats empty command as needing confirmation", () => {
    expect(assessCommand("   ").requiresConfirmation).toBe(true);
  });
});
